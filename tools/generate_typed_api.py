#!/usr/bin/env python3
"""Generate typed WAAPI Rust bindings into `src/api/generated/`.

Reads JSON schemas from `tools/waapi_schemas/<version>/` across all discovered
version directories and override rules from `tools/overrides.json`, emitting:
- `src/api/generated/object_types.rs` (`ObjectType` enum from `WObjects.xml`)
- `src/api/generated/properties.rs` (`Property` enum from `WObjects.xml`)
- `src/api/generated/primitives.rs` (shared enums, refs, `WwiseObject`, etc.)
- `src/api/generated/ak/...` (per-endpoint `Args` / `Options` / `Response` / `Payload` structs)
- `src/api/generated/clients.rs` (chained namespace client structs on `WaapiClient`)
- `src/api/generated/mod.rs`
"""

from __future__ import annotations

import shutil
import subprocess
from typing import Dict

from generator import (
    DISCOVERED_ENDPOINTS,
    DISCOVERED_TOPICS,
    FALLBACK_WARNINGS,
    OUT_DIR,
    PILOT_ENDPOINTS,
    SCHEMA_DIR,
    SCHEMA_DIRS,
    TOPIC_ENDPOINTS,
    Ctx,
    Schemas,
    build_module_tree,
    clear_fallback_warnings,
    emit_module_tree,
    endpoint_base_name,
    gen_clients,
    gen_endpoint_file,
    gen_object_types,
    gen_primitives,
    gen_properties,
    gen_topic_file,
)


def main() -> None:
    clear_fallback_warnings()
    schemas = Schemas(SCHEMA_DIR, fallback_roots=SCHEMA_DIRS[:-1])
    endpoints: Dict[str, dict] = {}
    for uri in DISCOVERED_ENDPOINTS:
        ctx = Ctx(schemas, uri)
        content, exports, has_args, has_options, has_response = (
            gen_endpoint_file(ctx)
        )
        endpoints[uri] = {
            "content": content,
            "exports": exports,
            "has_args": has_args,
            "has_options": has_options,
            "has_response": has_response,
            "base": endpoint_base_name(uri),
            "ctx": ctx,
        }

    topics: Dict[str, dict] = {}
    for uri in DISCOVERED_TOPICS:
        ctx = Ctx(schemas, uri)
        content, exports, has_options = gen_topic_file(ctx)
        topics[uri] = {
            "content": content,
            "exports": exports,
            "has_options": has_options,
            "base": endpoint_base_name(uri),
            "ctx": ctx,
        }

    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)

    tree = build_module_tree({**endpoints, **topics})
    emit_module_tree(tree, OUT_DIR)

    ctxs = {uri: info["ctx"] for uri, info in endpoints.items()}
    (OUT_DIR / "object_types.rs").write_text(gen_object_types(SCHEMA_DIRS))
    (OUT_DIR / "properties.rs").write_text(gen_properties(SCHEMA_DIRS))
    (OUT_DIR / "primitives.rs").write_text(gen_primitives(schemas, ctxs))
    (OUT_DIR / "clients.rs").write_text(gen_clients(endpoints, topics))
    (OUT_DIR / "mod.rs").write_text(
        "// Auto-generated typed WAAPI bindings.\n"
        "// This file is generated by tools/generate_typed_api.py; do not edit by hand.\n\n"
        "/// Typed request, option, response, and payload types organized by WAAPI URI namespace.\n"
        "pub mod ak;\n"
        "/// Chained namespace client wrappers on [`crate::WaapiClient`].\n"
        "pub mod clients;\n"
        "/// Typed Wwise object type identifiers (`ObjectType`).\n"
        "pub mod object_types;\n"
        "/// Shared request/response types, enums, and query builders.\n"
        "pub mod primitives;\n"
        "/// Typed Wwise property, reference, and list identifiers (`Property`).\n"
        "pub mod properties;\n\n"
        "pub use object_types::ObjectType;\n"
        "pub use properties::Property;\n"
    )
    print(
        f"Generated {len(endpoints)} endpoints and {len(topics)} topics "
        f"(union of {len(SCHEMA_DIRS)} versions: {', '.join(d.name for d in SCHEMA_DIRS)}) "
        f"into {OUT_DIR}"
    )
    if FALLBACK_WARNINGS:
        by_uri: Dict[str, int] = {}
        for uri, _, _ in FALLBACK_WARNINGS:
            by_uri[uri] = by_uri.get(uri, 0) + 1
        print(
            f"Note: {len(FALLBACK_WARNINGS)} field(s) across {len(by_uri)} endpoint(s) "
            "fell back to serde_json::Value (unmapped complex/polymorphic schema nodes)."
        )
    subprocess.run(["cargo", "fmt"], cwd=OUT_DIR.parents[2], check=False)


if __name__ == "__main__":
    main()
